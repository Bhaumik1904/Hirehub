package com.hirehub.util;

import javafx.geometry.Insets;
import javafx.geometry.Pos;
import javafx.scene.Node;
import javafx.scene.control.Label;
import javafx.scene.control.Separator;
import javafx.scene.layout.HBox;
import javafx.scene.layout.Priority;
import javafx.scene.layout.Region;
import javafx.scene.layout.VBox;
import javafx.scene.text.Font;
import javafx.scene.text.FontPosture;
import javafx.scene.text.FontWeight;
import javafx.scene.text.Text;
import javafx.scene.text.TextFlow;

import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * MarkdownRenderer — lightweight, dependency-free JavaFX Markdown renderer.
 *
 * <p>Converts Markdown text generated by GroqCloud AI into a structured hierarchy
 * of styled JavaFX nodes (Headings, Bullet Lists, Numbered Lists, Callouts, and TextFlows
 * with inline bold, italic, code, and link styles).</p>
 *
 * <p>Eliminates raw Markdown markers (**, *, ###, -, 1.) while preserving the
 * premium HireHub white and navy design system.</p>
 */
public final class MarkdownRenderer {

    private static final String FONT_FAMILY = "Segoe UI";
    private static final double BASE_FONT_SIZE = 13.5;

    // Pattern to match inline tokens: **bold**, `code`, *italic*, _italic_, [text](url)
    private static final Pattern INLINE_PATTERN = Pattern.compile(
            "(\\*\\*(.+?)\\*\\*)|(__([^_]+?)__)|(`([^`]+?)`)|(\\*([^*]+?)\\*)|(_([^_]+?)_)|(\\[([^\\]]+)\\]\\(([^\\)]+)\\))"
    );

    // Pattern for numbered list: e.g. "1. " or " 2) "
    private static final Pattern NUMBERED_LIST_PATTERN = Pattern.compile(
            "^(\\s*)(\\d+[\\.\\)])\\s+(.*)$"
    );

    // Pattern for bullet list: e.g. "* ", "- ", "+ ", "• "
    private static final Pattern BULLET_LIST_PATTERN = Pattern.compile(
            "^(\\s*)[\\*\\-\\+•]\\s+(.*)$"
    );

    private MarkdownRenderer() {}

    /**
     * Renders Markdown text into the target VBox container.
     *
     * @param container    the target VBox to receive the rendered nodes
     * @param markdownText the raw Markdown text from AI service
     */
    public static void renderInto(VBox container, String markdownText) {
        if (container == null) return;
        container.getChildren().clear();

        if (markdownText == null || markdownText.isBlank()) {
            Label emptyLbl = new Label("(No response content)");
            emptyLbl.setStyle("-fx-text-fill: #6B7280; -fx-font-style: italic; -fx-font-size: 13.5px;");
            container.getChildren().add(emptyLbl);
            return;
        }

        String[] lines = markdownText.split("\\r?\\n");
        boolean lastWasBlank = false;

        for (String rawLine : lines) {
            String trimmed = rawLine.trim();

            // Blank line handling
            if (trimmed.isEmpty()) {
                if (!lastWasBlank) {
                    Region spacer = new Region();
                    spacer.setPrefHeight(6.0);
                    container.getChildren().add(spacer);
                    lastWasBlank = true;
                }
                continue;
            }
            lastWasBlank = false;

            // 1. Horizontal separator (---, ***, ___)
            if (trimmed.matches("^[\\*\\-_]{3,}$")) {
                Separator sep = new Separator();
                sep.setStyle("-fx-padding: 6 0;");
                container.getChildren().add(sep);
                continue;
            }

            // 2. Heading 1 (# ...)
            if (trimmed.startsWith("# ")) {
                String headingText = cleanHeadingText(trimmed.substring(2));
                Label h1 = new Label(headingText);
                h1.setFont(Font.font(FONT_FAMILY, FontWeight.BOLD, 18.0));
                h1.setStyle("-fx-text-fill: #1A2B5E; -fx-font-weight: bold; -fx-padding: 10 0 4 0;");
                h1.setWrapText(true);
                container.getChildren().add(h1);
                continue;
            }

            // 3. Heading 2 (## ...)
            if (trimmed.startsWith("## ")) {
                String headingText = cleanHeadingText(trimmed.substring(3));
                Label h2 = new Label(headingText);
                h2.setFont(Font.font(FONT_FAMILY, FontWeight.BOLD, 16.0));
                h2.setStyle("-fx-text-fill: #1A2B5E; -fx-font-weight: bold; -fx-padding: 8 0 3 0;");
                h2.setWrapText(true);
                container.getChildren().add(h2);
                continue;
            }

            // 4. Heading 3 or 4 (### ... or #### ...)
            if (trimmed.startsWith("### ") || trimmed.startsWith("#### ")) {
                int prefixLen = trimmed.startsWith("#### ") ? 5 : 4;
                String headingText = cleanHeadingText(trimmed.substring(prefixLen));
                Label h3 = new Label(headingText);
                h3.setFont(Font.font(FONT_FAMILY, FontWeight.BOLD, 14.5));
                h3.setStyle("-fx-text-fill: #2563EB; -fx-font-weight: bold; -fx-padding: 6 0 2 0;");
                h3.setWrapText(true);
                container.getChildren().add(h3);
                continue;
            }

            // 5. Blockquote / Callout (> ...)
            if (trimmed.startsWith("> ")) {
                String quoteText = trimmed.substring(2).trim();
                HBox callout = createCalloutBox(quoteText);
                container.getChildren().add(callout);
                continue;
            }

            // 6. Numbered list item: e.g. "1. ..."
            Matcher numMatcher = NUMBERED_LIST_PATTERN.matcher(rawLine);
            if (numMatcher.matches()) {
                String indent = numMatcher.group(1);
                String number = numMatcher.group(2);
                String content = numMatcher.group(3);

                HBox row = createListItemRow(number, content, indent.length(), true);
                container.getChildren().add(row);
                continue;
            }

            // 7. Bullet list item: e.g. "* ..." or "- ..."
            Matcher bulletMatcher = BULLET_LIST_PATTERN.matcher(rawLine);
            if (bulletMatcher.matches()) {
                String indent = bulletMatcher.group(1);
                String content = bulletMatcher.group(2);

                HBox row = createListItemRow("•", content, indent.length(), false);
                container.getChildren().add(row);
                continue;
            }

            // 8. Regular paragraph / text line
            TextFlow paragraph = createTextFlow(trimmed);
            container.getChildren().add(paragraph);
        }
    }

    /**
     * Renders a prominent error or notice banner inside the container.
     */
    public static void renderErrorInto(VBox container, String errorMessage) {
        if (container == null) return;
        container.getChildren().clear();

        VBox box = new VBox(8);
        box.setStyle("-fx-background-color: #FEF2F2; -fx-border-color: #F87171; "
                + "-fx-border-width: 1.5; -fx-border-radius: 8; -fx-background-radius: 8; "
                + "-fx-padding: 16 20;");

        HBox header = new HBox(10);
        header.setAlignment(Pos.CENTER_LEFT);

        Label icon = new Label("⚠");
        icon.setStyle("-fx-font-size: 18px; -fx-text-fill: #DC2626; -fx-font-weight: bold;");

        Label title = new Label("AI Service Notice");
        title.setFont(Font.font(FONT_FAMILY, FontWeight.BOLD, 15.0));
        title.setStyle("-fx-text-fill: #991B1B;");

        header.getChildren().addAll(icon, title);

        Label msg = new Label(errorMessage != null ? errorMessage : "An unexpected issue occurred.");
        msg.setFont(Font.font(FONT_FAMILY, BASE_FONT_SIZE));
        msg.setStyle("-fx-text-fill: #7F1D1D;");
        msg.setWrapText(true);

        box.getChildren().addAll(header, msg);
        container.getChildren().add(box);
    }

    // =========================================================================
    // Internal Helper Builders
    // =========================================================================

    private static HBox createListItemRow(String bulletSymbol, String contentText, int indentSpaces, boolean isNumber) {
        HBox row = new HBox(8);
        row.setAlignment(Pos.TOP_LEFT);

        double leftPadding = 8.0 + (indentSpaces * 4.0);
        row.setPadding(new Insets(2, 0, 2, leftPadding));

        Label bulletLabel = new Label(bulletSymbol);
        bulletLabel.setFont(Font.font(FONT_FAMILY, FontWeight.BOLD, isNumber ? 13.0 : 14.0));
        bulletLabel.setStyle("-fx-text-fill: #2563EB; -fx-font-weight: bold;");
        bulletLabel.setMinWidth(isNumber ? 26.0 : 16.0);
        bulletLabel.setAlignment(Pos.TOP_RIGHT);

        TextFlow contentFlow = createTextFlow(contentText);
        HBox.setHgrow(contentFlow, Priority.ALWAYS);

        row.getChildren().addAll(bulletLabel, contentFlow);
        return row;
    }

    private static HBox createCalloutBox(String text) {
        HBox callout = new HBox(10);
        callout.setStyle("-fx-background-color: #F8FAFC; -fx-border-color: #2563EB; "
                + "-fx-border-width: 0 0 0 3.5; -fx-padding: 10 14; -fx-background-radius: 4;");
        callout.setAlignment(Pos.CENTER_LEFT);

        TextFlow flow = createTextFlow(text);
        HBox.setHgrow(flow, Priority.ALWAYS);

        callout.getChildren().add(flow);
        return callout;
    }

    private static TextFlow createTextFlow(String text) {
        TextFlow flow = new TextFlow();
        flow.setLineSpacing(4.0);

        List<Text> textNodes = parseInline(text);
        flow.getChildren().addAll(textNodes);
        return flow;
    }

    /**
     * Parses inline markdown tokens into a sequence of styled JavaFX Text nodes.
     */
    public static List<Text> parseInline(String text) {
        List<Text> nodes = new ArrayList<>();
        if (text == null || text.isEmpty()) return nodes;

        Matcher m = INLINE_PATTERN.matcher(text);
        int lastEnd = 0;

        while (m.find()) {
            if (m.start() > lastEnd) {
                nodes.add(createStyledText(text.substring(lastEnd, m.start()), false, false, false, false));
            }

            if (m.group(1) != null) {
                // **bold**
                nodes.add(createStyledText(m.group(2), true, false, false, false));
            } else if (m.group(3) != null) {
                // __bold__
                nodes.add(createStyledText(m.group(4), true, false, false, false));
            } else if (m.group(5) != null) {
                // `code`
                nodes.add(createStyledText(m.group(6), false, false, true, false));
            } else if (m.group(7) != null) {
                // *italic*
                nodes.add(createStyledText(m.group(8), false, true, false, false));
            } else if (m.group(9) != null) {
                // _italic_
                nodes.add(createStyledText(m.group(10), false, true, false, false));
            } else if (m.group(11) != null) {
                // [link](url)
                String linkText = m.group(12);
                nodes.add(createStyledText(linkText, true, false, false, true));
            }

            lastEnd = m.end();
        }

        if (lastEnd < text.length()) {
            nodes.add(createStyledText(text.substring(lastEnd), false, false, false, false));
        }

        return nodes;
    }

    private static Text createStyledText(String text, boolean bold, boolean italic, boolean code, boolean link) {
        Text t = new Text(text);

        if (code) {
            t.setFont(Font.font("Consolas", 12.5));
            t.setStyle("-fx-fill: #1E293B;");
        } else {
            FontWeight weight = bold ? FontWeight.BOLD : FontWeight.NORMAL;
            FontPosture posture = italic ? FontPosture.ITALIC : FontPosture.REGULAR;
            t.setFont(Font.font(FONT_FAMILY, weight, posture, BASE_FONT_SIZE));

            if (link) {
                t.setStyle("-fx-fill: #2563EB; -fx-underline: true;");
            } else if (bold) {
                t.setStyle("-fx-fill: #0F172A; -fx-font-weight: bold;");
            } else {
                t.setStyle("-fx-fill: #374151;");
            }
        }

        return t;
    }

    private static String cleanHeadingText(String text) {
        if (text == null) return "";
        // Strip bold asterisks from heading text if present (e.g. "### **1. Matching Skills**")
        return text.replaceAll("\\*\\*", "").replaceAll("__", "").trim();
    }
}


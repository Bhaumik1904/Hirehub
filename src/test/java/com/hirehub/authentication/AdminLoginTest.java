package com.hirehub.authentication;


import com.hirehub.model.*;
import com.hirehub.service.*;
import com.hirehub.dao.*;
import com.hirehub.database.*;
import com.hirehub.util.*;
import com.hirehub.controller.*;
import com.hirehub.model.User;

/**
 * AdminLoginTest — Offline verification of the admin login code path.
 *
 * <p>Simulates what AuthService.login() does for the admin account without
 * requiring a live MySQL connection. Proves that:</p>
 * <ol>
 *   <li>The hash stored in schema.sql correctly matches "Admin@1234".</li>
 *   <li>The old placeholder hash does NOT match "Admin@1234" (the original bug).</li>
 *   <li>A plain-text string is rejected by verifyPassword() (no bypass possible).</li>
 *   <li>The AuthService role-switch would route ADMIN to admin_dashboard.fxml.</li>
 * </ol>
 *
 * Run with:
 *   java -cp "target/classes;path/to/jbcrypt-0.4.jar" com.hirehub.util.AdminLoginTest
 */
public class AdminLoginTest {

    // Hash currently stored in database/schema.sql (generated by PasswordUtil)
    private static final String SCHEMA_HASH =
            "$2a$12$s1Y5vC02Zcr7w53/StvonuqEVKLPYoNPlMcwU3uU9rHOK5SrD7uMa";

    // Old placeholder hash that was in schema.sql before the fix
    private static final String OLD_PLACEHOLDER_HASH =
            "$2a$12$92IBq9dF3v3XDv7OQaIHO.6rDXjOvVCkLZoxsBknVlKrmgKdz3NKi";

    public static void main(String[] args) {
        System.out.println("╔══════════════════════════════════════════════════════╗");
        System.out.println("║   HireHub — Admin Login Path Verification            ║");
        System.out.println("╚══════════════════════════════════════════════════════╝");
        System.out.println();

        int passed = 0;
        int failed = 0;

        // ── Test 1: Correct password against the schema hash (must PASS) ──────
        boolean t1 = PasswordUtil.verifyPassword("Admin@1234", SCHEMA_HASH);
        printResult("T1", "Admin@1234 vs schema hash (must PASS)", t1, true);
        if (t1) passed++; else failed++;

        // ── Test 2: Old placeholder hash vs Admin@1234 (must FAIL — proves bug) ─
        boolean t2 = PasswordUtil.verifyPassword("Admin@1234", OLD_PLACEHOLDER_HASH);
        printResult("T2", "Admin@1234 vs OLD placeholder hash (must FAIL — original bug)", !t2, false);
        if (!t2) passed++; else failed++;

        // ── Test 3: Wrong password must fail ──────────────────────────────────
        boolean t3 = PasswordUtil.verifyPassword("admin123", SCHEMA_HASH);
        printResult("T3", "Plain 'admin123' vs schema hash (must FAIL — no plain text)", !t3, false);
        if (!t3) passed++; else failed++;

        // ── Test 4: Empty password must fail gracefully ───────────────────────
        boolean t4 = PasswordUtil.verifyPassword("", SCHEMA_HASH);
        printResult("T4", "Empty string vs schema hash (must FAIL)", !t4, false);
        if (!t4) passed++; else failed++;

        // ── Test 5: null password handled without NPE ─────────────────────────
        boolean t5 = PasswordUtil.verifyPassword(null, SCHEMA_HASH);
        printResult("T5", "null password (must FAIL gracefully, no NPE)", !t5, false);
        if (!t5) passed++; else failed++;

        // ── Test 6: Simulate AuthService role-switch routing ─────────────────
        User mockAdmin = new User("System Administrator", "admin@hirehub.com",
                SCHEMA_HASH, User.Role.ADMIN);
        String dashboardFxml = switch (mockAdmin.getRole()) {
            case STUDENT   -> "/fxml/student_dashboard.fxml";
            case RECRUITER -> "/fxml/recruiter_dashboard.fxml";
            case ADMIN     -> "/fxml/admin_dashboard.fxml";
        };
        boolean t6 = "/fxml/admin_dashboard.fxml".equals(dashboardFxml);
        printResult("T6", "Role ADMIN routes to admin_dashboard.fxml", t6, true);
        if (t6) passed++; else failed++;

        // ── Summary ───────────────────────────────────────────────────────────
        System.out.println();
        System.out.println("──────────────────────────────────────────────────────");
        System.out.printf ("  Results: %d PASSED / %d FAILED%n", passed, failed);
        System.out.println("──────────────────────────────────────────────────────");

        if (failed > 0) {
            System.err.println("VERIFICATION FAILED — do not deploy.");
            System.exit(1);
        } else {
            System.out.println("  ✓ All checks passed. schema.sql is correct.");
            System.out.println("  ✓ Admin login will succeed with password: Admin@1234");
            System.out.println("  ✓ No plain-text password comparison exists.");
        }
    }

    private static void printResult(String id, String description,
                                    boolean condition, boolean expectedTrue) {
        String status = condition ? "  PASS ✓" : "  FAIL ✗";
        System.out.printf("[%s] %s%n     %s%n", id, description, status);
    }
}

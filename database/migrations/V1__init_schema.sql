-- Create database (safe — skips if already exists)
CREATE DATABASE IF NOT EXISTS hirehub_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE hirehub_db;

-- =============================================================================
-- TABLE: users
-- Core user entity — stores all registered users (students, recruiters, admin)
-- =============================================================================

CREATE TABLE IF NOT EXISTS users (
    id            INT           NOT NULL AUTO_INCREMENT,
    full_name     VARCHAR(100)  NOT NULL,
    email         VARCHAR(150)  NOT NULL,
    password_hash VARCHAR(255)  NOT NULL,   -- BCrypt hash (never plain text)
    role          ENUM('STUDENT', 'RECRUITER', 'ADMIN') NOT NULL DEFAULT 'STUDENT',
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),
    UNIQUE KEY uq_email (email)
) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_unicode_ci
  COMMENT='Central user table for all HireHub accounts';

